// One-time backfill: pulls existing data from the Google Sheets (via the
// same Apps Script `action=fetch` endpoint the frontend already uses) and
// generates a SQL file that loads it into the new Supabase schema.
//
// Usage:
//   node scripts/migrate-to-supabase.mjs > supabase/migrations/9999_backfill.sql
//
// This script only READS from Sheets and WRITES a local .sql file — it never
// touches the DB itself, so it's safe to inspect the output before applying.

import { readFileSync } from 'fs';

const envText = readFileSync(new URL('../.env', import.meta.url), 'utf8');
const env = Object.fromEntries(
  envText.split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#')).map(l => {
    const idx = l.indexOf('=');
    return [l.slice(0, idx).trim(), l.slice(idx + 1).trim()];
  })
);

const SCRIPT_URL = env.VITE_SCRIPT_URL;
const SHEET_ID = env.VITE_SHEET_ID;

async function fetchSheet(name) {
  const res = await fetch(`${SCRIPT_URL}?action=fetch&sheet=${encodeURIComponent(name)}&spreadsheetId=${SHEET_ID}`);
  const json = await res.json();
  if (!json.success) throw new Error(`Failed to fetch "${name}": ${json.error}`);
  return json.data.slice(1); // drop header row
}

// ---- SQL escaping helpers --------------------------------------------------
const esc = (v) => {
  if (v === null || v === undefined || v === '') return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const num = (v) => {
  if (v === null || v === undefined || v === '') return '0';
  const n = parseFloat(String(v).replace(/[$,\s]/g, ''));
  return isNaN(n) ? '0' : String(n);
};
const dateVal = (v) => (v ? esc(v) : 'NULL');

const out = [];
const log = (s) => out.push(s);

log('-- ============================================================================');
log('-- 9999_backfill.sql — auto-generated by scripts/migrate-to-supabase.mjs');
log('-- Generated ' + new Date().toISOString());
log('-- ============================================================================');
log('begin;');
log('');

// ---- item_master (from Master-Dropdown, deduped by item name) -------------
const masterRows = await fetchSheet('Master-Dropdown');
const itemMap = new Map(); // item_name (lowercased) -> {type, dept, unit, rental, damage}
const issuerSet = new Set();
const eventTypeSet = new Set();

for (const row of masterRows) {
  const [type, itemName, dept, , unit, rental, damage, issuer, eventType] = row;
  if (itemName && String(itemName).trim() !== '' && !itemMap.has(itemName.trim().toLowerCase())) {
    itemMap.set(itemName.trim().toLowerCase(), {
      itemName: itemName.trim(), type: type || '', dept: dept || '', unit: unit || '',
      rental: rental || 0, damage: damage || 0
    });
  }
  if (issuer && String(issuer).trim() !== '') issuerSet.add(issuer.trim());
  if (eventType && String(eventType).trim() !== '') eventTypeSet.add(eventType.trim());
}

// Straggler items: present in INVENTORY / Add-Stock / Issued / Return but
// missing from Master-Dropdown — add them too so every FK resolves.
const invRows = await fetchSheet('INVENTORY');
for (const row of invRows) {
  const [, , type, dept, itemName] = row;
  if (itemName && !itemMap.has(String(itemName).trim().toLowerCase())) {
    itemMap.set(String(itemName).trim().toLowerCase(), {
      itemName: String(itemName).trim(), type: type || '', dept: dept || '', unit: '', rental: 0, damage: 0
    });
  }
}

log('-- item_master (' + itemMap.size + ' unique items)');
for (const { itemName, type, dept, unit, rental, damage } of itemMap.values()) {
  log(`insert into item_master (item_name, inventory_type, department, unit, rental_price, damage_price) values (${esc(itemName)}, ${esc(type)}, ${esc(dept)}, ${esc(unit)}, ${num(rental)}, ${num(damage)}) on conflict (item_name) do nothing;`);
}
log('');

log('-- issuers (' + issuerSet.size + ')');
for (const name of issuerSet) log(`insert into issuers (name) values (${esc(name)}) on conflict (name) do nothing;`);
log('');

log('-- event_types (' + eventTypeSet.size + ')');
for (const name of eventTypeSet) log(`insert into event_types (name) values (${esc(name)}) on conflict (name) do nothing;`);
log('');

// ---- profiles (Login) ------------------------------------------------------
const loginRows = await fetchSheet('Login');
log('-- profiles (' + loginRows.length + ')');
for (const [name, username, password, role, deployLink] of loginRows) {
  if (!username) continue;
  const roleVal = (role === 'admin' ? 'admin' : 'user');
  log(`insert into profiles (name, username, password, role, deploy_link) values (${esc(name)}, ${esc(username)}, ${esc(password)}, ${esc(roleVal)}::role_enum, ${esc(deployLink)}) on conflict (username) do nothing;`);
}
log('');

// ---- stock_transactions (Add-Stock + Re-Purchase) --------------------------
async function stockTxns(sheetName, source) {
  const rows = await fetchSheet(sheetName);
  log(`-- ${sheetName} -> stock_transactions (${rows.length}, source=${source})`);
  for (const row of rows) {
    const [timestamp, serialNo, , , , itemName, vendor, qty, unit, perUnit, imageUrl, remarks] = row;
    if (!itemName) continue;
    log(`insert into stock_transactions (source, serial_no, item_id, vendor_name, qty, unit, per_unit, image_url, remarks, created_at)
select ${esc(source)}::stock_source_enum, ${esc(serialNo)}, im.id, ${esc(vendor)}, ${num(qty)}, ${esc(unit)}, ${num(perUnit)}, ${esc(imageUrl)}, ${esc(remarks)}, coalesce(${dateVal(timestamp)}::timestamptz, now())
from item_master im where lower(im.item_name) = lower(${esc(itemName)});`);
  }
  log('');
}
await stockTxns('Add-Stock', 'add_stock');
await stockTxns('Re-Purchase', 're_purchase');

// ---- issues (Issued) --------------------------------------------------------
const issuedRows = await fetchSheet('Issued');
log('-- Issued -> issues (' + issuedRows.length + ')');
for (const row of issuedRows) {
  const [timestamp, serialNo, , , , itemName, partyName, eventDate, issueQty, damageRate, rentingRate,
    opening, closing, , venueName, imageUrl, remarks, eventType, , forType, issuer, dishes] = row;
  if (!itemName) continue;
  const forTypeVal = (forType === 'H3' || forType === 'Rent') ? `${esc(forType)}::for_type_enum` : 'NULL';
  log(`insert into issues (serial_no, item_id, party_name, event_date, issue_qty, damage_rate, renting_rate, opening_balance, closing_balance, venue_name, image_url, remarks, event_type_id, for_type, issuer_id, dishes, created_at)
select ${esc(serialNo)}, im.id, ${esc(partyName)}, ${dateVal(eventDate)}::date, ${num(issueQty)}, ${num(damageRate)}, ${num(rentingRate)}, ${num(opening)}, ${num(closing)}, ${esc(venueName)}, ${esc(imageUrl)}, ${esc(remarks)}, et.id, ${forTypeVal}, iss.id, ${esc(dishes)}, coalesce(${dateVal(timestamp)}::timestamptz, now())
from item_master im
left join event_types et on lower(et.name) = lower(${esc(eventType)})
left join issuers iss on lower(iss.name) = lower(${esc(issuer)})
where lower(im.item_name) = lower(${esc(itemName)});`);
}
log('');

// ---- returns (Return) --------------------------------------------------
// NOTE: Issued and Return each have their OWN independent serial_no counter
// in the legacy sheets (confirmed: Return's SN-004/SN-006 don't even exist
// in Issued) — they are NOT a shared key. There is no reliable column in
// the legacy data linking a return to its originating issue row, so
// issue_id is intentionally left NULL on backfill rather than guessing via
// a coincidental serial_no match. Going forward, the app should set
// issue_id directly (it'll have the real issue UUID at write-time).
const returnRows = await fetchSheet('Return');
log('-- Return -> returns (' + returnRows.length + ') — issue_id left NULL, see note above');
for (const row of returnRows) {
  const [timestamp, serialNo, , , , itemName, partyName, eventDate, returnDate, issueQty, returnQty,
    damageQty, missingQty, damageRate, rentingRate, opening, closing, totalBalance, imageUrl, remarks, , forType] = row;
  if (!itemName) continue;
  const forTypeVal = (forType === 'H3' || forType === 'Rent') ? `${esc(forType)}::for_type_enum` : 'NULL';
  log(`insert into returns (serial_no, issue_id, item_id, party_name, event_date, return_date, issue_qty, return_qty, damage_qty, missing_qty, damage_rate, renting_rate, opening_balance, closing_balance, total_balance, image_url, remarks, for_type, created_at)
select ${esc(serialNo)}, NULL, im.id, ${esc(partyName)}, ${dateVal(eventDate)}::date, ${dateVal(returnDate)}::date, ${num(issueQty)}, ${num(returnQty)}, ${num(damageQty)}, ${num(missingQty)}, ${num(damageRate)}, ${num(rentingRate)}, ${num(opening)}, ${esc(closing)}, ${num(totalBalance)}, ${esc(imageUrl)}, ${esc(remarks)}, ${forTypeVal}, coalesce(${dateVal(timestamp)}::timestamptz, now())
from item_master im
where lower(im.item_name) = lower(${esc(itemName)});`);
}
log('');

// ---- inventory_daily_snapshot (History INVENTORY) --------------------------
const historyRows = await fetchSheet('History INVENTORY');
log('-- History INVENTORY -> inventory_daily_snapshot (' + historyRows.length + ')');
for (const row of historyRows) {
  const [date, , itemName, totalPurchased, opening, closing, totalBalance, totalIssue, totalReturn, totalDamage, totalMissing] = row;
  if (!itemName || !date) continue;
  log(`insert into inventory_daily_snapshot (snapshot_date, item_id, total_purchased, opening_balance, closing_balance, total_balance, total_issue, total_return, total_damage, total_missing)
select ${dateVal(date)}::date, im.id, ${num(totalPurchased)}, ${num(opening)}, ${num(closing)}, ${num(totalBalance)}, ${num(totalIssue)}, ${num(totalReturn)}, ${num(totalDamage)}, ${num(totalMissing)}
from item_master im where lower(im.item_name) = lower(${esc(itemName)})
on conflict (snapshot_date, item_id) do nothing;`);
}
log('');

log('-- inventory_current is fully derived by triggers from the inserts above —');
log('-- no direct backfill needed/possible (it recalculates on every insert).');
log('');
log('commit;');

console.log(out.join('\n'));
